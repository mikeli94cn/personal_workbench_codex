  const textNodes = [], attributes = [];
  function translate() {
    document.documentElement.lang = language;
    for (const [node, original] of textNodes) node.nodeValue = original.replace(original.trim(), t(original.trim()));
    for (const [element, attribute, original] of attributes) element.setAttribute(attribute, t(original));
    document.querySelector('#language-select').value = language;
  }
  function setLanguage(value, persist = true) {
    if (!languages.includes(value)) return;
    language = value;
    if (persist) { try { localStorage.setItem(key, value); } catch {} }
    translate();
    window.dispatchEvent(new Event('languagechange'));
  }
